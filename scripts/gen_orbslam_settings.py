#!/usr/bin/env python3
"""
Write an ORB-SLAM3 RGB-D settings file from the attached OAK-D's factory
calibration, set up to match what CameraWorker actually publishes.

The intrinsics are those of the actual CAM_A output CameraWorker requests
(requestOutput(resolution, enableUndistortion=True)): the script runs that
output for one frame and reads the frame's ImgTransformation intrinsic
matrix, which includes the Camera node's resize and crop (default
ImgResizeMode.CROP: scale to cover, centre crop) and the undistortion. If the
frame has no valid transformation it falls back to
calib.getCameraIntrinsics(CAM_A, w, h), whose default keepAspectRatio=True
does the same scale-to-cover + centre crop, and warns if the two disagree.
Zero distortion (CameraWorker publishes undistorted frames), RGB order since
CameraWorker converts from DepthAI's BGR, and DepthMapFactor 1.0 because depth
is already in metres (CameraWorker divides by 1000). The device id is written
as Pilot.deviceId; CameraWorker checks it and the intrinsics at startup.

Calibration is per unit, so rerun this if the camera gets swapped. The OAK-D
has to be plugged in. --config and --output are relative to the repo root.

Usage:
    python scripts/gen_orbslam_settings.py                       # uses config.yaml
    python scripts/gen_orbslam_settings.py --config config_cpu.yaml
    python scripts/gen_orbslam_settings.py -o my_settings.yaml
"""

from __future__ import annotations

import argparse
import os
import sys

import yaml

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TEMPLATE = """%YAML:1.0
# Generated by scripts/gen_orbslam_settings.py — do not edit by hand.
# Device: {device_id}   Resolution: {width}x{height}   FPS: {fps}
# Intrinsics from: {source}

File.version: "1.0"

# checked by CameraWorker against the connected camera (ignored by ORB-SLAM3)
Pilot.deviceId: "{device_id}"

#--------------------------------------------------------------------------------------------
# Camera (undistorted RGB from CameraWorker, CAM_A)
#--------------------------------------------------------------------------------------------
Camera.type: "PinHole"

Camera1.fx: {fx:.6f}
Camera1.fy: {fy:.6f}
Camera1.cx: {cx:.6f}
Camera1.cy: {cy:.6f}

# CameraWorker publishes undistorted frames
Camera1.k1: 0.0
Camera1.k2: 0.0
Camera1.p1: 0.0
Camera1.p2: 0.0

Camera.width: {width}
Camera.height: {height}
Camera.fps: {fps}

# 0: BGR, 1: RGB (CameraWorker publishes RGB)
Camera.RGB: 1

#--------------------------------------------------------------------------------------------
# Depth (CameraWorker publishes metres)
#--------------------------------------------------------------------------------------------
RGBD.DepthMapFactor: 1.0

# Virtual stereo baseline (m) × this = close/far depth threshold
Stereo.b: {baseline:.6f}
Stereo.ThDepth: 40.0

#--------------------------------------------------------------------------------------------
# ORB Parameters
#--------------------------------------------------------------------------------------------
ORBextractor.nFeatures: 1200
ORBextractor.scaleFactor: 1.2
ORBextractor.nLevels: 8
ORBextractor.iniThFAST: 20
ORBextractor.minThFAST: 7

#--------------------------------------------------------------------------------------------
# Viewer Parameters (unused by the Python pipeline, required by ORB-SLAM3)
#--------------------------------------------------------------------------------------------
Viewer.KeyFrameSize: 0.05
Viewer.KeyFrameLineWidth: 1.0
Viewer.GraphLineWidth: 0.9
Viewer.PointSize: 2.0
Viewer.CameraSize: 0.08
Viewer.CameraLineWidth: 3.0
Viewer.ViewpointX: 0.0
Viewer.ViewpointY: -0.7
Viewer.ViewpointZ: -1.8
Viewer.ViewpointF: 500.0
"""


def live_intrinsics(dai, width: int, height: int, fps: float):
    """(K, source, device_id, calib) for CAM_A's output as CameraWorker requests it."""
    with dai.Pipeline() as pipeline:
        device = pipeline.getDefaultDevice()
        device_id = device.getDeviceId()
        calib = device.readCalibration()
        cam = pipeline.create(dai.node.Camera).build(dai.CameraBoardSocket.CAM_A, sensorFps=fps)
        q = cam.requestOutput((width, height), fps=fps, enableUndistortion=True).createOutputQueue()
        pipeline.start()
        frame = q.get()
        tr = frame.getTransformation()
        pipeline.stop()
    if tr.isValid():
        K = [list(r) for r in tr.getIntrinsicMatrix()]
        dist = [d for d in tr.getDistortionCoefficients() if abs(d) > 1e-9]
        if dist:
            print(f"warning: the undistorted output still reports distortion {dist}", file=sys.stderr)
        return K, "camera output (ImgTransformation)", device_id, calib
    K = calib.getCameraIntrinsics(dai.CameraBoardSocket.CAM_A, width, height)
    return K, "calibration", device_id, calib


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--config", default="config.yaml", help="pilot_core config to read resolution/fps from")
    parser.add_argument("-o", "--output", default="orbslam_oakd_rgbd.yaml", help="output settings file")
    args = parser.parse_args()

    try:
        import depthai as dai
    except ImportError:
        print("depthai is required: pip install 'depthai>=3.0'", file=sys.stderr)
        return 1

    with open(os.path.join(REPO_ROOT, args.config)) as f:
        cfg = yaml.safe_load(f) or {}
    width, height = cfg.get("resolution", [640, 400])
    fps = cfg.get("fps", 30)

    K, source, device_id, calib = live_intrinsics(dai, width, height, fps)
    K_calib = calib.getCameraIntrinsics(dai.CameraBoardSocket.CAM_A, width, height)
    if source != "calibration":
        diff = [abs(K[i][j] - K_calib[i][j]) / abs(K[i][j])
                for i, j in ((0, 0), (1, 1), (0, 2), (1, 2))]
        if max(diff) > 0.02:
            print(f"note: calibration-scaled intrinsics differ by up to {100 * max(diff):.1f}% "
                  f"from the camera output's ({K_calib}); using the camera output's")
    # left/right stereo baseline, cm -> m
    baseline = abs(calib.getBaselineDistance(dai.CameraBoardSocket.CAM_B, dai.CameraBoardSocket.CAM_C)) / 100.0

    out_path = os.path.join(REPO_ROOT, args.output)
    with open(out_path, "w") as f:
        f.write(TEMPLATE.format(
            device_id=device_id, width=width, height=height, fps=fps, source=source,
            fx=K[0][0], fy=K[1][1], cx=K[0][2], cy=K[1][2], baseline=baseline,
        ))
    print(f"Wrote {out_path}  (fx={K[0][0]:.1f} fy={K[1][1]:.1f} cx={K[0][2]:.1f} cy={K[1][2]:.1f}, b={baseline:.3f} m)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
